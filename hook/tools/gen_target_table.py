#!/usr/bin/env python3
"""Generate the bootstrap's pinned-build table from known-build.json.

WHY THIS IS GENERATED RATHER THAN PARSED AT RUNTIME
---------------------------------------------------
The hook's first job at attach is to prove the process is running the build it
was built for, and to do that it needs the expected values *before* it trusts
anything in the process.  Reading them from `known-build.json` at startup would
mean either shipping a JSON parser into a startup hook (and taking a dependency
for it) or parsing by hand in the one place where a parse bug is a silent wrong
answer.

So the values are compiled in, by this script, from the same file Phase 0's
fingerprint gate compares against.  There is still exactly one source of truth --
`known-build.json` -- and this script is the mechanical step between it and the
bootstrap.  `build.ps1` runs it before every managed build, and the output is
also committed so the bootstrap can be built by someone who does not have Python.

Usage:
    python gen_target_table.py                 # write the generated source
    python gen_target_table.py --check         # exit 1 if the file is stale
    python gen_target_table.py --json PATH
    python gen_target_table.py --out PATH

Exit codes: 0 = written/matching, 1 = stale or a problem with the input, 2 = usage.
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# tools/ -> hook/ -> repo root, then back into the managed tree.
DEFAULT_JSON = os.path.abspath(os.path.join(HERE, "..", "known-build.json"))
DEFAULT_OUT = os.path.abspath(
    os.path.join(HERE, "..", "managed", "Drelay.Bootstrap", "GeneratedBuildTable.cs")
)

TEMPLATE = '''// <auto-generated>
//   Generated by hook/tools/gen_target_table.py from
//   hook/known-build.json.  DO NOT EDIT BY HAND.
//
//   This file is the bootstrap's copy of the pinned build.  It is generated
//   rather than parsed so that the startup hook needs no JSON reader and no
//   I/O before it has proved which build it is in -- and so that there is one
//   source of truth (known-build.json) rather than two.
//
//   Regenerate with:  python hook/tools/gen_target_table.py
//   Or simply build:  hook/build.ps1  (runs it automatically)
// </auto-generated>

namespace Drelay.Bootstrap
{
    public static class GeneratedBuildTable
    {
        /// <summary>The known-build.json record this table was generated from.</summary>
        public const string RecordedOn = "{recorded}";
        // A verbatim string: recordedFrom is a Windows path, and a regular
        // literal would need every backslash doubled.  The first version of this
        // generator emitted the raw path and the C# compiler rejected it with
        // four CS1009s, which is the reason the @ is here and not decoration.
        public const string RecordedFrom = @"{recorded_from}";

        /// <summary>Game assembly identity, as Phase 0 pinned it.</summary>
        public const string GameVersion = "{game_version}";
        public const string AssemblyFileName = "{assembly_file}";
        /// <summary>
        /// The apphost's file name, derived from the assembly's rather than
        /// written down twice.  A self-contained .NET apphost is the assembly's
        /// name with .exe, and the launcher needs the name to start the game --
        /// so it comes from the same pinned record the hook identifies the
        /// assembly by, and a future rename moves both or neither.
        /// </summary>
        public const string ExecutableFileName = "{executable_file}";
        public const long AssemblySize = {assembly_size}L;
        /// <summary>
        /// THE OTHER APPHOST'S ASSEMBLY, WHICH IS A DIFFERENT BUILD.  Two apphosts ship
        /// together: the root DarzasDominion.exe is the one Phase 0 pinned and the only one the
        /// hook knows, and OpenGL\\DarzasDominion.exe carries its own assembly of a different
        /// size.  The launcher's auto-discovery compares a candidate directory's assembly against
        /// both numbers so that it can NAME the OpenGL install as the problem rather than
        /// reporting "not the pinned build" and leaving the user to guess
        /// (HANDOFF-LAUNCH-CONFIG.md section 7).  A record with no such value emits 0, which can
        /// never equal a real file's size.
        /// </summary>
        public const long AssemblySizeOpenGlVariant = {assembly_size_opengl}L;
        public const string AssemblySha256 = "{assembly_sha256}";
        public const string AssemblyMvid = "{assembly_mvid}";
        /// <summary>
        /// The Steam application id, used by the launcher's auto-discovery to find
        /// `steamapps\\appmanifest_&lt;id&gt;.acf` and with it the directory the user actually
        /// installed the game into.  Same source of truth as everything else here.
        /// </summary>
        public const int SteamAppId = {steam_app_id};

        /// <summary>Runtime the hook was built for.</summary>
        public const string RuntimeTfm = "{runtime_tfm}";
        public const string RuntimeVersion = "{runtime_version}";
        public const string RuntimeCoreclrBuild = "{runtime_coreclr_build}";
        public const bool RuntimeTieredCompilation = {runtime_tiered};

        /// <summary>
        /// The four detour targets.  The IL hash is the identity; the metadata
        /// token and the IL size are cross-checks that the spike reports on.
        /// </summary>
        public static readonly TargetSpec[] Targets = new TargetSpec[]
        {
{target_rows}        };

        public readonly struct TargetSpec
        {
            public readonly string Name;
            public readonly string DeclaringType;
            public readonly string MethodName;
            public readonly uint MetadataToken;
            public readonly int IlSize;
            public readonly string IlHash;
            public readonly string Role;

            public TargetSpec(string name, string declaringType, string methodName,
                              uint metadataToken, int ilSize, string ilHash, string role)
            {
                Name = name;
                DeclaringType = declaringType;
                MethodName = methodName;
                MetadataToken = metadataToken;
                IlSize = ilSize;
                IlHash = ilHash;
                Role = role;
            }
        }
    }
}
'''


def render(doc):
    game = doc.get("game", {})
    asm = doc.get("assembly", {})
    rt = doc.get("runtime", {})
    targets = doc.get("targetMethods", {})

    rows = []
    order = ["frameTick", "spawn", "collision", "escape"]    # Any target the record has that is not in the canonical order is included
    # too, so adding a target to known-build.json cannot be silently dropped by
    # this generator.  A record whose keys are all unknown still produces a
    # table; the native side is what refuses to install when a hash never
    # appears in the compilation stream.
    for key in order + [k for k in targets if not k.startswith("_") and k not in order]:
        t = targets.get(key)
        if not isinstance(t, dict) or "ilHash" not in t:
            continue
        # The token is formatted by this script, not by a format specifier in
        # the template.  Writing `0x{token:X}` puts the `X` inside the
        # replacement field, so Python parses "0x06001FC5X" as a hex literal and
        # every token comes out shifted left by four bits -- a wrong number that
        # still looks like a token, which is exactly the kind of error the
        # cross-check exists to catch and must not itself introduce.
        token = int(str(t.get("metadataToken", "0")).replace("0x", ""), 16)
        rows.append(
            '            new TargetSpec("{name}", "{type}", "{method}", 0x{token:08X}, '
            '{size}, "{hash}", "{role}"),'.format(
                name=key,
                type=t.get("declaringType", ""),
                method=t.get("name", ""),
                token=token,
                size=int(t.get("ilSize", 0)),
                hash=t.get("ilHash", ""),
                role=t.get("role", key),
            )
        )

    assembly_file = asm.get("file", "DarzasDominion.dll")
    executable_file = assembly_file
    if executable_file.lower().endswith(".dll"):
        executable_file = executable_file[:-4]
    executable_file += ".exe"

    # `str.format` is deliberately NOT used: the template is C#, so every brace
    # in it is a literal brace and would all have to be doubled.  Placeholder
    # substitution keeps the template readable as the C# it is.
    values = {
        "recorded": doc.get("recorded", ""),
        "recorded_from": doc.get("recordedFrom", ""),
        "game_version": game.get("version", ""),
        "assembly_file": assembly_file,
        "executable_file": executable_file,
        "assembly_size": int(asm.get("size", 0)),
        "assembly_size_opengl": int(asm.get("sizeOpenGlVariant", 0)),
        "steam_app_id": int(game.get("steamAppId", 0)),
        "assembly_sha256": asm.get("sha256", ""),
        "assembly_mvid": asm.get("mvid", ""),
        "runtime_tfm": rt.get("tfm", ""),
        "runtime_version": str(rt.get("version", "")),
        "runtime_coreclr_build": str(rt.get("coreclrBuild", "")),
        "runtime_tiered": "true" if rt.get("tieredCompilation") else "false",
        "target_rows": "\n".join(rows) + "\n" if rows else "",
    }

    text = TEMPLATE
    for key, value in values.items():
        text = text.replace("{" + key + "}", str(value))
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=DEFAULT_JSON, help="known-build.json to read")
    ap.add_argument("--out", default=DEFAULT_OUT, help="generated source to write")
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 when the file is stale")
    args = ap.parse_args()

    try:
        with open(args.json, "r", encoding="utf-8") as fh:
            doc = json.load(fh)
    except OSError as exc:
        print(f"cannot read {args.json}: {exc}", file=sys.stderr)
        return 1
    except json.JSONDecodeError as exc:
        print(f"{args.json} is not valid JSON: {exc}", file=sys.stderr)
        return 1

    text = render(doc)

    if args.check:
        try:
            with open(args.out, "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            print(f"{args.out} does not exist; run the generator", file=sys.stderr)
            return 1
        if current != text:
            print(f"{args.out} is STALE with respect to {args.json}", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
        return 0

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    n = text.count("new TargetSpec(")
    print(f"wrote {args.out} ({n} target(s) from {args.json})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
