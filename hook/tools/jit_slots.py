#!/usr/bin/env python3
"""Enumerate the ICorJitInfo vtable slot indices for a given dotnet/runtime release.

The slot index of a virtual method in the JIT/EE interface is a *derived* fact:
it is the declaration order of the method in corinfo.h, flattened across the
class hierarchy (ICorStaticInfo -> ICorDynamicInfo -> ICorJitInfo) and placed
after the four ICorJitCompiler slots that CILJit already occupies.

Nothing about that is stable across a runtime version, which is why
HOOK-ARCHITECTURE.md treats every slot index as "verify, do not assume".  This
tool re-derives the table from the runtime's own header for a named release so
the hook's constants can be *checked* rather than copied from a blog post.

The header is the same file the runtime is compiled from, so this is a strong
cross-check -- but it is not the shipped binary.  The authority remains the
loaded clrjit.dll/coreclr.dll, and the hook proves the slot it used by
comparing the token it read against the token Phase 0 already pinned in
known-build.json (see Drelay.Hook's --spike1.2 output).

Usage:
    python jit_slots.py                     # fetch release/9.0 and print the table
    python jit_slots.py --ref release/8.0
    python jit_slots.py --file icorjitinfoimpl_generated.h

The default source is `icorjitinfoimpl_generated.h`, not `corinfo.h`.  That file
is autogenerated by the runtime's own thunk generator and its header states that
it is "in exactly the same order, with exactly the same whitespace, as the
ICorJitInfo interface declaration" -- which is precisely the property a slot
index depends on.  (`corinfo.h` splits the interface across ICorStaticInfo,
ICorDynamicInfo and an internal ICorJitInfo that lives outside that header, so
parsing it alone undercounts; the generated file has all of them flattened.)

Exit codes: 0 = table produced, 1 = header could not be read, 2 = usage.
"""

import argparse
import re
import sys
import urllib.request

BASE = (
    "https://raw.githubusercontent.com/dotnet/runtime/{ref}"
    "/src/coreclr/inc/icorjitinfoimpl_generated.h"
)

# ICorJitCompiler's own virtuals, which occupy slots 0..3 of the concrete
# CILJit vtable.  compileMethod is slot 0 on every .NET version; the other
# three are ProcessShutdownWork, getVersionIdentifier and setTargetOS.  Only
# compileMethod may be detoured; the rest are listed so the arithmetic is
# visible rather than magic.
ICORJITCOMPILER_SLOTS = [
    "compileMethod",
    "ProcessShutdownWork",
    "getVersionIdentifier",
    "setTargetOS",
]

# Interfaces that are *flattened* into ICorJitInfo's vtable, in declaration
# order.  Each contributes its own virtuals before the next one's.
CLASS_ORDER = ["ICorStaticInfo", "ICorDynamicInfo", "ICorJitInfo"]

# A virtual declaration is one or more lines ending in "= 0;".  We capture the
# identifier immediately before the parameter list.  Operators and destructors
# would break this, but the JIT/EE interface has none.
VIRTUAL_RE = re.compile(r"virtual\s+(.*?)(\w+)\s*\(", re.S)
CLASS_RE = re.compile(r"^[ \t]*class\s+(\w+)\s*(?::\s*public\s+(\w+))?\s*$", re.M)


def strip_comments(text):
    """Remove // and /* */ comments so declarations do not hide inside prose."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def class_bodies(text):
    """Return {class name: (parent, body text)} for every class in the header.

    Bodies are found by brace matching from the class declaration, which is
    enough for this header: there are no braces inside comments by the time we
    get here, and the interface classes declare no inline bodies of their own
    that contain a stray unbalanced brace.
    """
    out = {}
    for m in CLASS_RE.finditer(text):
        name, parent = m.group(1), m.group(2)
        if parent is None:
            continue
        start = text.find("{", m.end())
        if start < 0:
            continue
        depth = 0
        for i in range(start, len(text)):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    out[name] = (parent, text[start + 1 : i])
                    break
    return out


def generated_virtuals(text):
    """Identifiers of every ICorJitInfo method, in declaration order.

    The generated header carries the declarations with `override` instead of
    `virtual ... = 0`, in the interface's exact order.  Each declaration is a
    return type on its own line followed by `name(` and a parameter list.  We
    therefore anchor on the *end* of a statement: an identifier immediately
    followed by `(`, whose statement terminates with `override;`.
    """
    names = []
    for m in re.finditer(r"(\w+)\s*\([^;{]*?override\s*;", text, re.S):
        names.append(m.group(1))
    return names


def virtuals(body):
    """Identifiers of the pure virtuals declared directly in a class body.

    Nested class bodies are cut first so a nested interface's virtuals are not
    attributed to the outer class.
    """
    body = re.sub(r"\{\s*[^{}]*?\}\s*;", ";", body, flags=re.S)  # drop inline enums/structs
    names = []
    for m in re.finditer(r"virtual\s+[^;{]*?=\s*0\s*;", body, re.S):
        decl = m.group(0)
        idm = re.findall(r"(\w+)\s*\(", decl)
        if idm:
            names.append(idm[-1])
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default="release/9.0", help="dotnet/runtime branch to read")
    ap.add_argument("--file", help="parse a local copy of the generated header")
    ap.add_argument("--all", action="store_true", help="print every slot, not just the tail")
    args = ap.parse_args()

    if args.file:
        try:
            with open(args.file, "r", encoding="utf-8", errors="replace") as fh:
                text = fh.read()
        except OSError as exc:
            print(f"cannot read {args.file}: {exc}", file=sys.stderr)
            return 1
        origin = args.file
    else:
        url = BASE.format(ref=args.ref)
        try:
            with urllib.request.urlopen(url, timeout=30) as resp:
                text = resp.read().decode("utf-8", "replace")
        except Exception as exc:  # noqa: BLE001 - one message is what the caller wants
            print(f"cannot fetch {url}: {exc}", file=sys.stderr)
            return 1
        origin = url

    text = strip_comments(text)

    slots = []
    for i, name in enumerate(ICORJITCOMPILER_SLOTS):
        slots.append((i, "ICorJitCompiler", name))

    chain = [n for n in ("ICorStaticInfo", "ICorDynamicInfo", "ICorJitInfo")]
    index = len(ICORJITCOMPILER_SLOTS)
    for vname in generated_virtuals(text):
        slots.append((index, "ICorJitInfo", vname))
        index += 1

    print(f"# ICorJitInfo vtable slots derived from {origin}")
    print(f"# flattened chain: ICorJitCompiler -> {' -> '.join(chain)}")
    print(f"# total slots (ICorJitCompiler + ICorJitInfo): {index}")
    print()
    print(f"{'slot':>6}  {'0x':>6}  {'interface':<16} method")
    for idx, cls, name in slots:
        if args.all or idx >= 4:
            print(f"{idx:>6}  0x{idx:02X}  {cls:<16} {name}")

    interesting = (
        "compileMethod",
        "getMethodDefFromMethod",
        "getFieldOffset",
        "getClassNumInstanceFields",
        "getFieldInClass",
        "isFieldStatic",
        "getStaticBaseAddress",
        "getMethodName",
    )
    print()
    print("# slots the hook cares about (.NET 9 reference -- the SHIPPED binary is the authority)")
    for idx, cls, name in slots:
        if name in interesting:
            print(f"  {name:<28} {idx:>4}  (0x{idx:X})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
